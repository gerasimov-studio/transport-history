import type { MetroLine, Station } from '../../types'

type StationRecord = [id: string, name: string, since: number, lat: number, lng: number]

function stations(lineId: string, records: StationRecord[]): Station[] {
  return records.map(([id, name, since, lat, lng]) => ({
    id: `${lineId}-${id}`,
    name,
    since,
    lat,
    lng,
  }))
}

